-- Data/hora actual em UTC no formato 'AAAA-MM-DD HH:MM:SS' (usado por omissão nas colunas criado_em)
CREATE OR REPLACE FUNCTION agora() RETURNS text LANGUAGE sql STABLE AS
$$ SELECT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS') $$;

