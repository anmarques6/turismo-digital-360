CREATE OR REPLACE VIEW v_receita_por_tipo AS
  SELECT tipo, COUNT(*) AS reservas, SUM(total) AS receita
  FROM reservas WHERE estado IN ('confirmada','concluida')
  GROUP BY tipo;

CREATE OR REPLACE VIEW v_reservas_detalhe AS
  SELECT r.*, u.nome AS cliente_nome, u.email AS cliente_email, u.telefone AS cliente_telefone
  FROM reservas r JOIN utilizadores u ON u.id = r.utilizador_id;

-- Actualiza a média ponderada e o número de avaliações do item quando entra uma nova avaliação
CREATE OR REPLACE FUNCTION fn_avaliacao_media() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE tabela text;
BEGIN
  IF NEW.aprovada <> 1 THEN RETURN NEW; END IF;
  tabela := CASE NEW.tipo WHEN 'experiencia' THEN 'experiencias' WHEN 'destino' THEN 'destinos' WHEN 'alojamento' THEN 'alojamentos'
                          WHEN 'restaurante' THEN 'restaurantes' WHEN 'tradutor' THEN 'tradutores' WHEN 'prato' THEN 'pratos' END;
  IF tabela IS NOT NULL THEN
    EXECUTE format('UPDATE %I SET rating = ROUND((rating * num_avaliacoes + $1) / (num_avaliacoes + 1), 1), num_avaliacoes = num_avaliacoes + 1 WHERE id = $2', tabela)
      USING NEW.nota, NEW.item_id;
  END IF;
  RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS trg_avaliacao_media ON avaliacoes;
CREATE TRIGGER trg_avaliacao_media AFTER INSERT ON avaliacoes FOR EACH ROW EXECUTE FUNCTION fn_avaliacao_media();

