  utilizador_id  INTEGER REFERENCES utilizadores(id) ON DELETE CASCADE,
  mensagens      TEXT    NOT NULL DEFAULT '[]',
  contexto       TEXT    NOT NULL DEFAULT '{}',
  atualizado_em  TEXT    NOT NULL DEFAULT agora()
);
CREATE TABLE IF NOT EXISTS enda_registos (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  utilizador_id  INTEGER REFERENCES utilizadores(id) ON DELETE SET NULL,
  tipo           TEXT    NOT NULL,                           -- fora_ambito | erro | sem_dados | resposta
  pergunta       TEXT,
  resposta       TEXT,
  detalhe        TEXT,
  revisto        SMALLINT NOT NULL DEFAULT 0,
  criado_em      TEXT    NOT NULL DEFAULT agora()
);

