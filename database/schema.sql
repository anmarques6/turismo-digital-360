  provincia     TEXT,
  latitude      DOUBLE PRECISION,
  longitude     DOUBLE PRECISION,
  coord_estado  TEXT,
  coord_fonte   TEXT,
  ativo         INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS jogos (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fonte_id      INTEGER REFERENCES fontes(id) ON DELETE SET NULL,
  externo_id    TEXT,
  modalidade    TEXT    NOT NULL DEFAULT 'Futebol',
  competicao    TEXT    NOT NULL,
  jornada       TEXT,
  casa          TEXT    NOT NULL,
  fora          TEXT    NOT NULL,
  data_hora     TEXT    NOT NULL,                            -- hora de Angola, AAAA-MM-DD HH:MM
  estadio       TEXT,
  estadio_id    INTEGER REFERENCES estadios(id) ON DELETE SET NULL,
  estado        TEXT    NOT NULL DEFAULT 'agendado',         -- agendado | ao vivo | terminado | adiado | cancelado
  golos_casa    INTEGER,
  golos_fora    INTEGER,
  bilhetes_url  TEXT,
  fonte_nome    TEXT,
  fonte_url     TEXT,
  confianca     TEXT    NOT NULL DEFAULT 'fonte identificada',
  notas         TEXT,
  verificado_em TEXT,
  atualizado_em TEXT,
  ativo         INTEGER NOT NULL DEFAULT 1,
  criado_em     TEXT    NOT NULL DEFAULT agora()
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_jogos_externo ON jogos(fonte_id, externo_id) WHERE externo_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_jogos_data ON jogos(data_hora);

-- Roteiros guardados pelos turistas
CREATE TABLE IF NOT EXISTS roteiros (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  utilizador_id  INTEGER NOT NULL REFERENCES utilizadores(id) ON DELETE CASCADE,
  titulo         TEXT    NOT NULL,
  cidade         TEXT,
  data_inicio    TEXT,
  dias           INTEGER NOT NULL DEFAULT 1,
  orcamento      INTEGER,
  pessoas        INTEGER NOT NULL DEFAULT 1,
  interesses     TEXT,                                       -- JSON
  transporte     TEXT,
  acessibilidade TEXT,
  itens          TEXT    NOT NULL DEFAULT '[]',              -- JSON: [{dia, periodo, tipo, item_id, nome, nota}]
  criado_em      TEXT    NOT NULL DEFAULT agora(),
  atualizado_em  TEXT    NOT NULL DEFAULT agora()
);
CREATE INDEX IF NOT EXISTS idx_roteiros_utilizador ON roteiros(utilizador_id);

-- ENDA: contexto da conversa por sessão (apagado ao fim de 24 h) e registo de respostas para revisão
CREATE TABLE IF NOT EXISTS enda_sessoes (
